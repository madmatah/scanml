"""Shared services and FastAPI dependencies of the routes."""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Annotated

from fastapi import Depends, HTTPException, Request

from ..auth import Authenticator
from ..config import Settings
from ..library import LibraryService
from ..ocr_client import OcrClient

UUID_PATTERN = r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"
_UUID = re.compile(UUID_PATTERN)


@dataclass(frozen=True)
class Services:
    settings: Settings
    library: LibraryService
    auth: Authenticator
    ocr: OcrClient


# Dependencies are coroutines so that they run on the event loop thread, the
# only one allowed to use the database connection (sync ones run in a pool).
async def get_services(request: Request) -> Services:
    return request.app.state.services


async def require_auth(request: Request) -> None:
    services: Services = request.app.state.services
    services.auth.check(request)


ServicesDep = Annotated[Services, Depends(get_services)]


def is_uuid(value: str) -> bool:
    """IDs are UUIDs, lowercase and hyphenated, generated by the clients."""
    return bool(_UUID.fullmatch(value))


def require_uuid(value: str, field: str) -> str:
    if not is_uuid(value):
        raise HTTPException(422, f"{field} must be a lowercase hyphenated UUID")
    return value


def public_url(services: Services, request: Request) -> str:
    """URL the phone uses to reach this server (PUBLIC_URL, else this request's origin)."""
    return services.settings.public_url or str(request.base_url).rstrip("/")
