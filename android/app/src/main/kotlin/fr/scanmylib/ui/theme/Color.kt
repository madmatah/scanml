// "Paper & Ink": warm paper neutrals, a teal accent and ocher for what needs a look. The medium- and
// high-contrast variants move each role's tone, its hue and chroma kept, until it reaches the
// contrast that Material's curves ask at those levels (material-color-utilities,
// MaterialDynamicColors), against the darkest surface in light and the lightest in dark.

internal fun pickColorScheme(isDark: Boolean, contrast: Contrast): ColorScheme = when (contrast) {
    Contrast.STANDARD -> if (isDark) DarkColors else LightColors
    Contrast.MEDIUM -> if (isDark) DarkMediumContrastColors else LightMediumContrastColors
    Contrast.HIGH -> if (isDark) DarkHighContrastColors else LightHighContrastColors
}

