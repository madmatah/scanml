"""A document's folder is named after its slug, and a page's files after its key. Locating a scan touches no disk. A
write replaces a file at once, so that a reader sees the old content or the new. A page's Markdown is written last, so
that its presence means that its OCR output is complete; it is empty until then. Nothing is deleted: a replaced OCR
output, a deleted page and a deleted document move to the library's trash, and a trash method returns the folder it
moved them to, or None when there was nothing to move. Only the files the api serves resolve, and only inside their
document's folder. A failure of the disk raises OSError, and reading the Markdown of a document whose file is missing
raises FileNotFoundError.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import PurePath
from typing import Protocol

from ..domain.assemble import DocumentMetadata, IndexMetadata
from .ocr_engine import RawOcrResult


class LibraryFiles(Protocol):
    def prepare(self) -> None: ...
    def has_folder(self, slug: str) -> bool: ...
    def create_folder(self, slug: str) -> None: ...
    def locate_scan(self, slug: str, key: str, extension: str) -> PurePath: ...
    def write_scan(self, slug: str, key: str, extension: str, encoded_scan: bytes) -> None: ...
    def read_page_markdown(self, slug: str, key: str) -> str: ...
    def write_page_outputs(
        self, slug: str, key: str, markdown: str, images: Sequence[tuple[str, bytes]], raw: RawOcrResult
    ) -> None: ...
    def trash_page(self, slug: str, key: str, extension: str) -> PurePath | None: ...
    def trash_document(self, slug: str) -> PurePath | None: ...
    def has_document_markdown(self, slug: str) -> bool: ...
    def read_document_markdown(self, slug: str) -> str: ...
    def resolve_document_file(self, slug: str, relative: str) -> PurePath | None: ...
    def export_entries(self, slug: str, include_scans: bool) -> Sequence[tuple[str, PurePath]]: ...


class PublishedFiles(Protocol):
    def read_page_markdown(self, slug: str, key: str) -> str: ...
    def write_document(self, slug: str, markdown: str, metadata: DocumentMetadata) -> None: ...
    def write_index(self, markdown: str, metadata: IndexMetadata) -> None: ...
